%   data = import14CfromExcel(totCols,workbook,worksheet,head) imports the first
%   TOTCOLS from sheet WORKSHEET in the Excel file WORKBOOK. 
%   The spreadsheet must be roganised in the following way
%
%       FIRST LINE:     column number 
%       SECOND LINE:    'num' or 'txt' or 'nominal' to indicate if the column must
%                       be imported as NUMerical, TXTual, or NOMINAL
%       THIRD LINE:     column name
%   
%       Example
%       1       2       3
%       num     txt     num
%       id      sex     age
%       230     M       22.4
%       432     F       52.1
%
%   OUTPUT
%       DATA    dataset containing totCols

%% Importing data from the Excel sheet

if nargin == 1
    [filename, pathname] = uigetfile({'*.xls', 'Excel 97-2004 only'},'Choose file to import');
    workbook = [pathname filename];
    worksheet =  'import';
