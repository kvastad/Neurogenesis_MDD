    kindRow = head(1);
    headerRow = head(2);
    dataRow = head(3);
else
    kindRow = 2;
    headerRow = 3;
    dataRow = 4;
end

[~, ~, kindCol] = xlsread(workbook,worksheet);

    
kindCol = kindCol(kindRow,1:totCols);

numCol = find(strcmp(kindCol,'num'));
textCol = find(strcmp(kindCol,'txt'));
nominalCol = find(strncmp(kindCol,'nominal',3));

if isempty(numCol) && isempty(textCol) && isempty(nominalCol)
    error('carbonDating:import14CfromExcel:field','No NUM, TXT or NOMINAL column found. Line 2 of the Excel sheet must contain ''num'' or ''txt''.');
end

if length(numCol)+length(textCol)+length(nominalCol) == length(kindCol)
    fprintf('Found %d numerical cols, %d text cols and %d nominal cols\n',length(numCol),length(textCol),length(nominalCol));
else
    error('carbonDating:import14CfromExcel:field','Missing NUM, TXT or NOMINAL entries. Line 2 of the Excel sheet must contain ''num'' or ''txt''.');
end
    
% Import the data


[~, ~, raw] = xlsread(workbook,worksheet);


